    <script>
        (function() {
            const form = document.getElementById("enquiryForm");

            const fields = {
                fullName: {
                    el: fullName,
                    err: fullNameErr,
                    validate: v => v.trim().length >= 3 ? "" : "Full name is required."
                },
                email: {
                    el: email,
                    err: emailErr,
                    validate: v => /^[^\s@]+@[^\s@]+\.[^\s@]{2,}$/.test(v.trim()) ? "" : "Valid email required."
                },
                contact: {
                    el: contact,
                    err: contactErr,
                    validate: v => (v.replace(/\D/g, '').length === 10) ? "" : "Valid 10-digit contact required."
                },
                qualification: {
                    el: qualification,
                    err: qualificationErr,
                    validate: v => v ? "" : "Qualification required."
                },
                city: {
                    el: city,
                    err: cityErr,
                    validate: v => v.trim().length >= 2 ? "" : "City required."
                },
                captcha: {
                    el: captcha,
                    err: captchaErr,
                    validate: v => v.trim().length >= 5 ? "" : "Captcha required."
                },
            };

            function setErr(k, msg) {
                fields[k].err.textContent = msg;
                fields[k].err.classList.toggle("hidden", !msg);
            }

            function validateAll() {
                let ok = true;
                Object.keys(fields).forEach(k => {
                    if (k === "contact") fields[k].el.value = fields[k].el.value.replace(/\D/g, '').slice(0, 10);
                    const msg = fields[k].validate(fields[k].el.value);
                    setErr(k, msg);
                    if (msg) ok = false;
                });
                return ok;
            }

            form.addEventListener("submit", (e) => {
                if (!validateAll()) e.preventDefault();
            });

            document.getElementById("refreshCaptcha")?.addEventListener("click", () => {
                document.getElementById("captchaImg").src = "./captcha.php?t=" + Date.now();
            });
        })();
    </script>

